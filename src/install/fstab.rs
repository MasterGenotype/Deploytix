/// Return the fstab filesystem type string, default mount options, and fsck
/// pass number for a boot partition.
///
/// Only ext4 supports reliable automatic boot-time fsck (pass 2).
/// btrfs, xfs, f2fs, and zfs must not be fsck'd at boot (pass 0).
fn boot_fs_fstab_entry(boot_filesystem: &Filesystem) -> (&'static str, &'static str, u8) {
    match boot_filesystem {
        Filesystem::Ext4 => ("ext4", "defaults,noatime", 0),
        Filesystem::Btrfs => ("btrfs", "subvol=@boot,defaults,noatime,compress=zstd", 0),
        Filesystem::Xfs => ("xfs", "defaults,noatime", 0),
        Filesystem::F2fs => ("f2fs", "defaults,noatime", 0),
        Filesystem::Zfs => ("zfs", "zfsutil,defaults,noatime", 0),
    }
}

/// Determine the correct fsck pass number for a data partition.
///
/// Only ext4 supports reliable automatic boot-time fsck:
///   - pass 1 for the root filesystem
///   - pass 2 for all other ext4 filesystems
///
/// btrfs, xfs, f2fs, and zfs must never be automatically fsck'd at boot
/// (pass 0).  btrfs uses its own internal integrity mechanisms; xfs and
/// f2fs fsck tools are not safe to run automatically; zfs handles its
/// own scrubbing.
fn fsck_pass(filesystem: &Filesystem, mount_point: &str) -> u8 {
    match filesystem {
        Filesystem::Ext4 if mount_point == "/" => 1,
        Filesystem::Ext4 => 2,
        _ => 0,
    }
}

/// Return the fstab filesystem type string and default mount options for a
/// data partition.
fn fs_fstab_entry(filesystem: &Filesystem) -> (&'static str, &'static str) {
    match filesystem {
        Filesystem::Btrfs => ("btrfs", "defaults,noatime,compress=zstd"),
        Filesystem::Ext4 => ("ext4", "defaults,noatime"),
        Filesystem::Xfs => ("xfs", "defaults,noatime"),
        Filesystem::F2fs => ("f2fs", "defaults,noatime"),
        Filesystem::Zfs => ("zfs", "zfsutil,defaults,noatime"),
    }
}

/// Append standard ZFS dataset fstab entries.
///
/// ZFS datasets with `mountpoint=legacy` are referenced by dataset name
/// (e.g., `rpool/ROOT`) rather than by UUID.
fn append_zfs_dataset_entries(content: &mut String) {
    for (ds, mp) in ZFS_DATASETS {
        let pass = 0; // ZFS handles its own fsck; pass is always 0
        content.push_str(&format!(
            "{}  {}  zfs  zfsutil,defaults,noatime  0  {}\n",
            ds, mp, pass
        ));
    }
}

/// Append the ZFS boot dataset fstab entry.
fn append_zfs_boot_entry(content: &mut String) {
    content.push_str(&format!(
        "\n# Boot dataset (ZFS)\n\
         {}  /boot  zfs  zfsutil,defaults,noatime  0  0\n",
        ZFS_BOOT_DATASET
    ));
}

/// Generate fstab using UUIDs
/// Handles both regular partitions and btrfs subvolume layouts
pub fn generate_fstab(
    cmd: &CommandRunner,
    device: &str,
    layout: &ComputedLayout,
    install_root: &str,
    filesystem: &Filesystem,
    boot_filesystem: &Filesystem,
    immutable: bool,
) -> Result<()> {
    // Check if this layout uses subvolumes
    if layout.uses_subvolumes() {
        return generate_fstab_with_subvolumes(
            cmd,
            device,
            layout,
            install_root,
            filesystem,
            boot_filesystem,
            immutable,
        );
    }

    info!(
        "Generating /etc/fstab for {} partitions on {}",
        layout.partitions.len(),
        device
    );

    if cmd.is_dry_run() {
        println!("  [dry-run] Would generate fstab with entries:");
        for part in &layout.partitions {
            if let Some(ref mp) = part.mount_point {
                println!("    UUID=<uuid> {} <fstype> defaults 0 1", mp);
            } else if part.is_swap {
                println!("    UUID=<uuid> none swap defaults 0 0");
            }
        }
        return Ok(());
    }

    let mut fstab_content = String::new();
    fstab_content.push_str("# /etc/fstab: static file system information.\n");
    fstab_content.push_str("# Generated by Deploytix\n");
    fstab_content.push_str("#\n");
    fstab_content.push_str("# <file system> <mount point> <type> <options> <dump> <pass>\n\n");

    // ZFS data filesystem: use dataset names instead of partition UUIDs
    if *filesystem == Filesystem::Zfs {
        append_zfs_dataset_entries(&mut fstab_content);

        // EFI and swap still use UUIDs
        for part in &layout.partitions {
            let part_path = partition_path(device, part.number);
            if part.is_efi {
                let uuid = get_partition_uuid(&part_path)?;
                fstab_content.push_str(&format!(
                    "UUID={}\t/boot/efi\tvfat\tumask=0077,defaults\t0\t0\n",
                    uuid
                ));
            } else if part.is_swap {
                let uuid = get_partition_uuid(&part_path)?;
                fstab_content.push_str(&format!("UUID={}\tnone\tswap\tdefaults\t0\t0\n", uuid));
            } else if part.is_boot_fs {
                // Boot entry handled separately based on boot_filesystem
                // (caller must append boot entry if not ZFS boot pool)
            }
        }
    } else {
        for part in &layout.partitions {
            let part_path = partition_path(device, part.number);
            let uuid = get_partition_uuid(&part_path)?;

            if part.is_swap {
                fstab_content.push_str(&format!("UUID={}\tnone\tswap\tdefaults\t0\t0\n", uuid));
            } else if let Some(ref mount_point) = part.mount_point {
                // Determine filesystem type and options based on configuration
                let (fstype, options, pass) = if part.is_efi {
                    ("vfat".to_string(), "umask=0077,defaults".to_string(), 0)
                } else if part.is_boot_fs {
                    let (bfs, bopts, bpass) = boot_fs_fstab_entry(boot_filesystem);
                    (bfs.to_string(), bopts.to_string(), bpass)
                } else {
                    let options = match filesystem {
                        Filesystem::Btrfs => "defaults,noatime,compress=zstd".to_string(),
                        _ => "defaults,noatime".to_string(),
                    };
                    (
                        filesystem.to_string(),
                        options,
                        fsck_pass(filesystem, mount_point),
                    )
                };

                fstab_content.push_str(&format!(
                    "UUID={}\t{}\t{}\t{}\t0\t{}\n",
                    uuid, mount_point, fstype, options, pass
                ));
            }
        }
    }

    // Write fstab
    let fstab_path = format!("{}/etc/fstab", install_root);
    fs::create_dir_all(format!("{}/etc", install_root))?;
    let mut file = fs::File::create(&fstab_path)?;
    file.write_all(fstab_content.as_bytes())?;

    info!("Fstab written to {}", fstab_path);
    Ok(())
}

/// Header explaining why `/`, `/usr` and `/etc` are absent from an immutable
/// system's fstab. Mirrors the equivalent note in [`generate_fstab_lvm_ab`].
const INITRAMFS_OWNED_NOTE: &str = "\
# Immutable root: /, /usr and /etc are mounted by the mountcrypt initramfs\n\
# hook, from the .deploytix-pair marker inside whichever root subvolume the\n\
# kernel cmdline selected (the base @ or a @deploytix-sets/<id>/root snapshot\n\
# set). They are intentionally NOT listed here: an fstab entry can only name\n\
# the base @/@usr/@etc, and `mount -a` would mount those over a booted\n\
# snapshot set, hiding everything `deploytix update` installed into it.\n\n";

/// fstab entries that give a read-only immutable root its writable paths.
///
/// `/` is mounted read-only and — deliberately — is *not* covered by an
/// overlayfs, so that it stays a real btrfs mount that `grub-probe`,
/// grub-btrfs and `findmnt` can work with. That leaves the handful of
/// directories which live inside `/` and still have to be written:
///
/// - `/tmp` as disk-backed btrfs `@tmp` on the root FS (not a half-RAM tmpfs;
///   see `docs/TMP_DISK_BACKED.md`). Boot wipe via tmpfiles keeps it ephemeral;
/// - `/root`, `/opt` and `/srv` bind-mounted out of the writable `@var`, so
///   they persist across reboots *and* across snapshot sets.
///
/// Bind mounts rather than symlinks: the `filesystem` package owns these three
/// as directories, and replacing them with symlinks makes every update of that
/// package conflict. `/var` is already mounted by the `mountcrypt` hook before
/// switch_root, so the bind sources exist by the time fstab is processed.
///
/// Not covered: `/mnt` and `/media` stay read-only. They are mount points, so
/// mounting *onto* them still works; only creating new subdirectories under
/// them at runtime fails, which is what `/run/media` is for.
///
/// `root_fs_uuid` is the UUID of the root btrfs that holds `@tmp`.
fn immutable_writable_paths(root_fs_uuid: &str) -> String {
    let mut s = String::from(
        "\n# Writable paths for the read-only root. `/` is a plain read-only\n\
         # btrfs mount (no overlay), so these are given writable homes\n\
         # explicitly. /tmp is disk-backed btrfs @tmp on the root FS (not RAM\n\
         # tmpfs); tmpfiles boot-clean keeps it ephemeral. The rest live on\n\
         # @var and persist.\n",
    );
    s.push_str(&crate::immutable::tmp::tmp_fstab_entry(root_fs_uuid));
    for (source, target) in crate::immutable::WRITABLE_BIND_PATHS {
        s.push_str(&format!("{source}  {target}  none  bind  0  0\n"));
    }
    // The pacman database goes the other way: out of the shared /var and into
    // the snapshotted /usr, so that it rolls back with the files it describes.
    s.push_str(&crate::immutable::pacman_db::fstab_entry());
    s.push('\n');
    s
}

/// Generate fstab for layouts using btrfs subvolumes
fn generate_fstab_with_subvolumes(
    cmd: &CommandRunner,
    device: &str,
    layout: &ComputedLayout,
    install_root: &str,
    filesystem: &Filesystem,
    boot_filesystem: &Filesystem,
    // True only for the btrfs immutable backend. It leaves `/`, `/usr` and
    // `/etc` out, because the initramfs mounts them from the booted set's
    // .deploytix-pair marker and listing them here would let `mount -a` shadow
    // that set with the base subvolumes. Pass false for a plain install and for
    // the LVM A/B backend, which has its own fstab.
    immutable: bool,
) -> Result<()> {
    let subvolumes = layout.subvolumes.as_ref().ok_or_else(|| {
        crate::utils::error::DeploytixError::ConfigError(
            "Layout reports subvolumes in use but subvolumes field is None".to_string(),
        )
    })?;
    info!(
        "Generating /etc/fstab with {} btrfs subvolumes",
        subvolumes.len()
    );

    // Find the root partition (the one with btrfs subvolumes)
    let root_part = layout
        .partitions
        .iter()
        .find(|p| p.name == "ROOT")
        .ok_or_else(|| {
            crate::utils::error::DeploytixError::ConfigError(
                "No ROOT partition found for subvolume layout".to_string(),
            )
        })?;

    if cmd.is_dry_run() {
        println!("  [dry-run] Would generate fstab with btrfs subvolumes:");
        for sv in subvolumes {
            if immutable && crate::immutable::initramfs_owned_mount(&sv.mount_point) {
                continue;
            }
            println!(
                "    UUID=<ROOT_UUID> {} btrfs subvol={},{} 0 {}",
                sv.mount_point,
                sv.name,
                sv.mount_options,
                0 // btrfs: no boot-time fsck
            );
        }
        return Ok(());
    }

    let root_path = partition_path(device, root_part.number);
    let root_uuid = get_partition_uuid(&root_path)?;

    let mut content = String::from(
        "# /etc/fstab: static file system information.\n\
         # Generated by Deploytix - Btrfs subvolume layout\n\
         #\n\
         # <file system> <mount point> <type> <options> <dump> <pass>\n\n",
    );

    if immutable {
        content.push_str(INITRAMFS_OWNED_NOTE);
    }

    // Add subvolume entries
    for sv in subvolumes {
        // Immutable model: `/`, `/usr` and `/etc` are mounted by the initramfs
        // from the booted root's pairing marker. Listing them here would make
        // `mount -a` shadow a booted snapshot set with the base subvolumes.
        if immutable && crate::immutable::initramfs_owned_mount(&sv.mount_point) {
            continue;
        }
        let pass = 0; // btrfs: no boot-time fsck
        content.push_str(&format!(
            "UUID={}  {}  btrfs  subvol={},{}  0  {}\n",
            root_uuid, sv.mount_point, sv.name, sv.mount_options, pass,
        ));
    }

    // Add other partitions (BOOT, EFI, swap, and per-partition btrfs subvolumes).
    for part in &layout.partitions {
        if part.name == "ROOT" {
            continue; // Already handled via subvolumes above
        }

        let part_path = partition_path(device, part.number);
        let uuid = get_partition_uuid(&part_path)?;

        if part.is_swap {
            content.push_str(&format!(
                "\n# Swap partition\nUUID={}  none  swap  defaults  0  0\n",
                uuid
            ));
        } else if part.is_efi {
            content.push_str(&format!(
                "\n# EFI System Partition\nUUID={}  /boot/efi  vfat  umask=0077,defaults  0  0\n",
                uuid
            ));
        } else if part.is_boot_fs {
            // BOOT partition: btrfs gets @boot subvolume, others get a plain entry
            if *boot_filesystem == Filesystem::Btrfs {
                content.push_str(&format!(
                    "\n# Boot partition (btrfs @boot subvolume)\nUUID={}  /boot  btrfs  subvol=@boot,defaults,noatime,compress=zstd  0  0\n",
                    uuid
                ));
            } else {
                let (fstype, opts, pass) = boot_fs_fstab_entry(boot_filesystem);
                content.push_str(&format!(
                    "\n# Boot partition\nUUID={}  /boot  {}  {}  0  {}\n",
                    uuid, fstype, opts, pass
                ));
            }
        } else if let Some(ref mount_point) = part.mount_point {
            if let Some(ref subvol_name) = part.subvolume_name {
                // Btrfs data partition with its own dedicated subvolume.
                content.push_str(&format!(
                    "\n# {} partition (btrfs {} subvolume)\nUUID={}  {}  btrfs  subvol={},defaults,noatime,compress=zstd  0  0\n",
                    part.name, subvol_name, uuid, mount_point, subvol_name
                ));
                // /var also hosts @log (→ /var/log) on the same btrfs filesystem.
                if mount_point == "/var" {
                    let log_subvol = mount_point_to_subvol_name("/var/log");
                    content.push_str(&format!(
                        "UUID={}  /var/log  btrfs  subvol={},defaults,noatime,compress=zstd  0  0\n",
                        uuid, log_subvol
                    ));
                }
            } else {
                // Non-btrfs data partition or btrfs partition without a named subvolume.
                let (fstype, options) = fs_fstab_entry(filesystem);
                let pass = fsck_pass(filesystem, mount_point);
                content.push_str(&format!(
                    "\nUUID={}  {}  {}  {}  0  {}\n",
                    uuid, mount_point, fstype, options, pass
                ));
            }
        }
    }

    // Last, so the bind sources under /var are already listed above them.
    if immutable {
        content.push_str(&immutable_writable_paths(&root_uuid));
    }

    let fstab_path = format!("{}/etc/fstab", install_root);
    fs::create_dir_all(format!("{}/etc", install_root))?;
    fs::write(&fstab_path, &content)?;

    info!(
        "Fstab written to {} with {} subvolume entries",
        fstab_path,
        subvolumes.len()
    );
    Ok(())
}

/// Generate fstab for multi-volume encrypted system
///
/// Creates entries for separate encrypted partitions (ROOT, USR, VAR, HOME)
/// mounted from /dev/mapper/Crypt-* devices.
/// Parameters for multi-volume encrypted fstab generation
pub struct MultiVolumeFstabParams<'a> {
    pub cmd: &'a CommandRunner,
    pub containers: &'a [LuksContainer],
    pub device: &'a str,
    pub layout: &'a ComputedLayout,
    pub filesystem: &'a Filesystem,
    pub boot_filesystem: &'a Filesystem,
    pub swap_type: &'a SwapType,
    /// Absolute path of the swap file in the target, for `SwapType::FileZram`.
    /// Differs on an immutable root -- see `configure::swap::swap_file_path`.
    pub swap_file: &'a str,
    pub install_root: &'a str,
    /// Transactional immutable root: mount `/` and `/usr` read-only and add a
    /// writable `@etc` subvolume mounted at `/etc`.
    pub immutable: bool,
}

pub fn generate_fstab_multi_volume(params: &MultiVolumeFstabParams) -> Result<()> {
    let cmd = params.cmd;
    let containers = params.containers;
    let device = params.device;
    let layout = params.layout;
    let filesystem = params.filesystem;
    let boot_filesystem = params.boot_filesystem;
    let swap_type = params.swap_type;
    let swap_file = params.swap_file;
    let install_root = params.install_root;
    info!(
        "Generating /etc/fstab for {} encrypted volumes",
        containers.len()
    );

    if cmd.is_dry_run() {
        let (fstype, fsopts) = fs_fstab_entry(filesystem);
        println!("  [dry-run] Would generate fstab with encrypted volumes:");
        for container in containers {
            let mp = container.volume_name.to_lowercase();
            let mount_point = if mp == "root" {
                "/".to_string()
            } else {
                format!("/{}", mp)
            };
            let pass = fsck_pass(filesystem, &mount_point);
            println!(
                "    {} {} {} {} 0 {}",
                container.mapped_path, mount_point, fstype, fsopts, pass
            );
        }
        return Ok(());
    }

    let mut content = String::from(
        "# /etc/fstab: static file system information.\n\
         # Generated by Deploytix - Multi-volume encrypted system\n\
         #\n\
         # <file system> <mount point> <type> <options> <dump> <pass>\n\n",
    );
    if params.immutable {
        content.push_str(INITRAMFS_OWNED_NOTE);
    }

    // Add encrypted volume entries
    if layout.uses_subvolumes() {
        // With subvolumes: each container has named subvolumes (e.g. @, @usr, @var, @home)
        for container in containers {
            let fs_uuid = get_partition_uuid(&container.mapped_path)?;
            let svols = multi_volume_subvolumes(&container.volume_name);
            for sv in &svols {
                // Immutable model: `/`, `/usr` and `/etc` belong to the
                // initramfs, which mounts the booted root's paired trio. An
                // fstab entry can only name the base subvolume and would be
                // mounted over a booted snapshot set by `mount -a`.
                if params.immutable && crate::immutable::initramfs_owned_mount(&sv.mount_point) {
                    continue;
                }
                content.push_str(&format!(
                    "# {} (LUKS encrypted)\n\
                     UUID={}  {}  btrfs  subvol={},{}  0  0\n\n",
                    container.volume_name, fs_uuid, sv.mount_point, sv.name, sv.mount_options,
                ));
            }
        }
    } else {
        for container in containers {
            let mount_point = match container.volume_name.as_str() {
                "Root" => "/".to_string(),
                name => format!("/{}", name.to_lowercase()),
            };

            let pass = fsck_pass(filesystem, &mount_point);

            // Get UUID of the filesystem on the mapped device
            let fs_uuid = get_partition_uuid(&container.mapped_path)?;

            // Note: ZFS is blocked with multi-volume encryption at validation
            // time, so this path always uses a traditional filesystem.
            let (fstype, options) = fs_fstab_entry(filesystem);
            content.push_str(&format!(
                "# {} partition (LUKS encrypted)\n\
                 UUID={}  {}  {}  {}  0  {}\n\n",
                container.volume_name, fs_uuid, mount_point, fstype, options, pass
            ));
        }
    }

    // Add swap based on swap_type
    match swap_type {
        SwapType::Partition => {
            let swap_part = layout.partitions.iter().find(|p| p.is_swap);
            if let Some(swap) = swap_part {
                let swap_device = partition_path(device, swap.number);
                let swap_uuid = get_partition_uuid(&swap_device)?;
                content.push_str(&format!(
                    "# Swap partition\n\
                     UUID={}  none  swap  defaults  0  0\n\n",
                    swap_uuid
                ));
            }
        }
        SwapType::FileZram => {
            content.push_str(&format!(
                "# Swap file (ZRAM provides additional compressed swap)\n\
                 {}  none  swap  defaults  0  0\n\n",
                swap_file
            ));
        }
        SwapType::ZramOnly => {
            // No fstab entry needed - ZRAM is configured via service
            content.push_str("# Swap: ZRAM only (configured via service)\n\n");
        }
    }

    // Add BOOT partition
    let boot_part = layout.partitions.iter().find(|p| p.is_boot_fs);
    if let Some(boot) = boot_part {
        let boot_device = partition_path(device, boot.number);
        let boot_uuid = get_partition_uuid(&boot_device)?;
        let (boot_fstype, boot_opts, boot_pass) = boot_fs_fstab_entry(boot_filesystem);
        content.push_str(&format!(
            "# Boot partition\n\
             UUID={}  /boot  {}  {}  0  {}\n\n",
            boot_uuid, boot_fstype, boot_opts, boot_pass
        ));
    }

    // Add EFI partition
    let efi_part = layout.partitions.iter().find(|p| p.is_efi);
    if let Some(efi) = efi_part {
        let efi_device = partition_path(device, efi.number);
        let efi_uuid = get_partition_uuid(&efi_device)?;
        content.push_str(&format!(
            "# EFI System Partition\n\
             UUID={}  /boot/efi  vfat  umask=0077,defaults  0  0\n",
            efi_uuid
        ));
    }

    // Last, so the bind sources under /var are already listed above them.
    // @tmp lives on the Root container's btrfs (same FS as @ / @etc).
    if params.immutable {
        let root_uuid = containers
            .iter()
            .find(|c| c.volume_name == "Root")
            .map(|c| get_partition_uuid(&c.mapped_path))
            .transpose()?
            .ok_or_else(|| {
                crate::utils::error::DeploytixError::ConfigError(
                    "No Root container found for immutable @tmp fstab entry".to_string(),
                )
            })?;
        content.push_str(&immutable_writable_paths(&root_uuid));
    }

    let fstab_path = format!("{}/etc/fstab", install_root);
    fs::create_dir_all(format!("{}/etc", install_root))?;
    fs::write(&fstab_path, &content)?;

    info!(
        "Fstab written to {} with {} encrypted volumes",
        fstab_path,
        containers.len()
    );
    Ok(())
}

/// Parameters for LVM thin fstab generation
pub struct LvmThinFstabParams<'a> {
    pub cmd: &'a CommandRunner,
    pub vg_name: &'a str,
    pub thin_volumes: &'a [ThinVolumeDef],
    pub device: &'a str,
    pub layout: &'a ComputedLayout,
    pub filesystem: &'a Filesystem,
    pub swap_type: &'a SwapType,
    /// Absolute path of the swap file in the target, for `SwapType::FileZram`.
    /// Differs on an immutable root -- see `configure::swap::swap_file_path`.
    pub swap_file: &'a str,
    pub boot_mapped_device: Option<&'a str>,
    pub boot_filesystem: &'a Filesystem,
    pub install_root: &'a str,
}

/// Generate fstab for LVM thin provisioning layout
///
/// Creates entries for thin LVs mounted from /dev/vg/lv paths.
/// When `boot_mapped_device` is Some, the boot partition is encrypted and
/// the filesystem UUID should be read from the mapped device path.
pub fn generate_fstab_lvm_thin(params: &LvmThinFstabParams) -> Result<()> {
    let cmd = params.cmd;
    let vg_name = params.vg_name;
    let thin_volumes = params.thin_volumes;
    let device = params.device;
    let layout = params.layout;
    let swap_type = params.swap_type;
    let swap_file = params.swap_file;
    let boot_mapped_device = params.boot_mapped_device;
    let install_root = params.install_root;
    info!("Generating /etc/fstab for LVM thin volumes");

    if cmd.is_dry_run() {
        let filesystem = params.filesystem;
        let (fstype, fsopts) = fs_fstab_entry(filesystem);
        println!("  [dry-run] Would generate fstab with LVM thin volumes:");
        for vol in thin_volumes {
            let pass = fsck_pass(filesystem, &vol.mount_point);
            println!(
                "    /dev/{}/{} {} {} {} 0 {}",
                vg_name, vol.name, vol.mount_point, fstype, fsopts, pass
            );
        }
        println!(
            "    {}  {}  none  bind,nofail  0  0",
            crate::immutable::pacman_db::DB_DIR,
            crate::immutable::pacman_db::DB_MOUNT
        );
        return Ok(());
    }

    let mut content = String::from(
        "# /etc/fstab: static file system information.\n\
         # Generated by Deploytix - LVM Thin Provisioning layout\n\
         #\n\
         # <file system> <mount point> <type> <options> <dump> <pass>\n\n",
    );

    // Add LVM thin volume entries
    let filesystem = params.filesystem;
    for vol in thin_volumes {
        let lv_device = lv_path(vg_name, &vol.name);
        let fs_uuid = get_partition_uuid(&lv_device)?;
        let pass = fsck_pass(filesystem, &vol.mount_point);
        let (fstype, options) = fs_fstab_entry(filesystem);

        content.push_str(&format!(
            "# {} thin volume\n\
             UUID={}  {}  {}  {}  0  {}\n\n",
            vol.name, fs_uuid, vol.mount_point, fstype, options, pass
        ));
    }

    // Add swap based on swap_type
    match swap_type {
        SwapType::Partition => {
            // Add SWAP partition if present
            let swap_part = layout.partitions.iter().find(|p| p.is_swap);
            if let Some(swap) = swap_part {
                let swap_device = partition_path(device, swap.number);
                let swap_uuid = get_partition_uuid(&swap_device)?;
                content.push_str(&format!(
                    "# Swap partition\n\
                     UUID={}  none  swap  defaults  0  0\n\n",
                    swap_uuid
                ));
            }
        }
        SwapType::FileZram => {
            // Add swap file entry
            content.push_str(&format!(
                "# Swap file (ZRAM provides additional compressed swap)\n\
                 {}  none  swap  defaults  0  0\n\n",
                swap_file
            ));
        }
        SwapType::ZramOnly => {
            // No fstab entry needed - ZRAM is configured via service
            content.push_str("# Swap: ZRAM only (configured via service)\n\n");
        }
    }

    // Add BOOT partition
    // When boot is encrypted, use the mapped device path for the filesystem UUID
    // When boot is ZFS, use the boot dataset name instead of UUID
    if *params.boot_filesystem == Filesystem::Zfs {
        append_zfs_boot_entry(&mut content);
    } else {
        let (boot_fstype, boot_opts, boot_pass) = boot_fs_fstab_entry(params.boot_filesystem);
        if let Some(mapped_dev) = boot_mapped_device {
            let boot_uuid = get_partition_uuid(mapped_dev)?;
            content.push_str(&format!(
                "# Boot partition (LUKS1 encrypted)\n\
                 UUID={}  /boot  {}  {}  0  {}\n\n",
                boot_uuid, boot_fstype, boot_opts, boot_pass
            ));
        } else {
            let boot_part = layout.partitions.iter().find(|p| p.is_boot_fs);
            if let Some(boot) = boot_part {
                let boot_device = partition_path(device, boot.number);
                let boot_uuid = get_partition_uuid(&boot_device)?;
                content.push_str(&format!(
                    "# Boot partition\n\
                     UUID={}  /boot  {}  {}  0  {}\n\n",
                    boot_uuid, boot_fstype, boot_opts, boot_pass
                ));
            }
        }
    }

    // Add EFI partition
    let efi_part = layout.partitions.iter().find(|p| p.is_efi);
    if let Some(efi) = efi_part {
        let efi_device = partition_path(device, efi.number);
        let efi_uuid = get_partition_uuid(&efi_device)?;
        content.push_str(&format!(
            "# EFI System Partition\n\
             UUID={}  /boot/efi  vfat  umask=0077,defaults  0  0\n",
            efi_uuid
        ));
    }

    let fstab_path = format!("{}/etc/fstab", install_root);
    fs::create_dir_all(format!("{}/etc", install_root))?;
    fs::write(&fstab_path, &content)?;

    info!(
        "Fstab written to {} with {} LVM thin volumes",
        fstab_path,
        thin_volumes.len()
    );
    Ok(())
}

/// Parameters for LVM immutable A/B fstab generation.
pub struct LvmAbFstabParams<'a> {
    pub cmd: &'a CommandRunner,
    pub vg_name: &'a str,
    pub volumes: &'a [crate::disk::lvm::AbLvDef],
    pub device: &'a str,
    pub layout: &'a ComputedLayout,
    pub filesystem: &'a Filesystem,
    pub swap_type: &'a SwapType,
    /// Absolute path of the swap file in the target, for `SwapType::FileZram`.
    /// Differs on an immutable root -- see `configure::swap::swap_file_path`.
    pub swap_file: &'a str,
    pub boot_mapped_device: Option<&'a str>,
    pub boot_filesystem: &'a Filesystem,
    pub install_root: &'a str,
}

/// Generate `/etc/fstab` for the LVM immutable A/B (dm-verity) layout.
///
/// `/` (read-only dm-verity root, including `/usr`) and `/etc` (writable overlay)
/// are mounted by the `verity-ab` initramfs handler and therefore appear only as
/// comments here. The persistent `var`/`home` LVs, swap, `/boot`, and EFI are
/// emitted as normal stable-UUID entries for systemd to mount post-switch_root.
pub fn generate_fstab_lvm_ab(params: &LvmAbFstabParams) -> Result<()> {
    use crate::disk::lvm::AbVolumeRole;

    let cmd = params.cmd;
    let vg_name = params.vg_name;
    let device = params.device;
    let layout = params.layout;
    let filesystem = params.filesystem;
    let install_root = params.install_root;
    info!("Generating /etc/fstab for LVM immutable A/B layout");

    // Persistent, mounted data volumes (var, home) — hash/slot/etc LVs excluded.
    let data_vols: Vec<&crate::disk::lvm::AbLvDef> = params
        .volumes
        .iter()
        .filter(|v| v.role == AbVolumeRole::Data)
        .collect();

    if cmd.is_dry_run() {
        let (fstype, fsopts) = fs_fstab_entry(filesystem);
        println!("  [dry-run] Would generate immutable A/B fstab:");
        println!("    # / (dm-verity, ro) and /etc (overlay) mounted by verity-ab hook");
        for vol in &data_vols {
            let pass = fsck_pass(filesystem, &vol.mount_point);
            println!(
                "    /dev/{}/{} {} {} {} 0 {}",
                vg_name, vol.name, vol.mount_point, fstype, fsopts, pass
            );
        }
        return Ok(());
    }

    let mut content = String::from(
        "# /etc/fstab: static file system information.\n\
         # Generated by Deploytix - LVM immutable A/B (dm-verity) layout\n\
         #\n\
         # / (read-only dm-verity root, incl. /usr) and /etc (writable overlay)\n\
         # are mounted by the verity-ab initramfs handler from the active slot\n\
         # (deploytix.slot=/deploytix.roothash= on the kernel cmdline). They are\n\
         # intentionally NOT listed here.\n\
         #\n\
         # <file system> <mount point> <type> <options> <dump> <pass>\n\n",
    );

    // Persistent writable data volumes.
    for vol in &data_vols {
        let lv_device = lv_path(vg_name, &vol.name);
        let fs_uuid = get_partition_uuid(&lv_device)?;
        let pass = fsck_pass(filesystem, &vol.mount_point);
        let (fstype, options) = fs_fstab_entry(filesystem);
        content.push_str(&format!(
            "# {} volume (persistent, shared across slots)\n\
             UUID={}  {}  {}  {}  0  {}\n\n",
            vol.name, fs_uuid, vol.mount_point, fstype, options, pass
        ));
    }

    // The pacman database is the exception to that sharing: it lives inside the
    // slot's verity-sealed root and is bound back onto /var/lib/pacman, so a
    // slot flip takes the database with it. Written after the /var entry above,
    // which has to be mounted first for the bind target to exist.
    content.push_str(&crate::immutable::pacman_db::fstab_entry());
    content.push('\n');

    // Swap (mirrors the LVM thin path).
    match params.swap_type {
        SwapType::Partition => {
            if let Some(swap) = layout.partitions.iter().find(|p| p.is_swap) {
                let swap_device = partition_path(device, swap.number);
                let swap_uuid = get_partition_uuid(&swap_device)?;
                content.push_str(&format!(
                    "# Swap partition\nUUID={}  none  swap  defaults  0  0\n\n",
                    swap_uuid
                ));
            }
        }
        SwapType::FileZram => {
            content.push_str(&format!(
                "# Swap file (ZRAM provides additional compressed swap)\n\
                 {}  none  swap  defaults  0  0\n\n",
                params.swap_file
            ));
        }
        SwapType::ZramOnly => {
            content.push_str("# Swap: ZRAM only (configured via service)\n\n");
        }
    }

    // /boot (possibly LUKS1-encrypted) and EFI.
    if *params.boot_filesystem == Filesystem::Zfs {
        append_zfs_boot_entry(&mut content);
    } else {
        let (boot_fstype, boot_opts, boot_pass) = boot_fs_fstab_entry(params.boot_filesystem);
        if let Some(mapped_dev) = params.boot_mapped_device {
            let boot_uuid = get_partition_uuid(mapped_dev)?;
            content.push_str(&format!(
                "# Boot partition (LUKS1 encrypted)\nUUID={}  /boot  {}  {}  0  {}\n\n",
                boot_uuid, boot_fstype, boot_opts, boot_pass
            ));
        } else if let Some(boot) = layout.partitions.iter().find(|p| p.is_boot_fs) {
            let boot_device = partition_path(device, boot.number);
            let boot_uuid = get_partition_uuid(&boot_device)?;
            content.push_str(&format!(
                "# Boot partition\nUUID={}  /boot  {}  {}  0  {}\n\n",
                boot_uuid, boot_fstype, boot_opts, boot_pass
            ));
        }
    }

    if let Some(efi) = layout.partitions.iter().find(|p| p.is_efi) {
        let efi_device = partition_path(device, efi.number);
        let efi_uuid = get_partition_uuid(&efi_device)?;
        content.push_str(&format!(
            "# EFI System Partition\n\
             UUID={}  /boot/efi  vfat  umask=0077,defaults  0  0\n",
            efi_uuid
        ));
    }

    let fstab_path = format!("{}/etc/fstab", install_root);
    fs::create_dir_all(format!("{}/etc", install_root))?;
    fs::write(&fstab_path, &content)?;
    info!(
        "Immutable A/B fstab written to {} ({} persistent data volumes)",
        fstab_path,
        data_vols.len()
    );
    Ok(())
}

/// Add swap file entry to an existing fstab
pub fn append_swap_file_entry(
    config: &crate::config::DeploymentConfig,
    install_root: &str,
) -> Result<()> {
    let fstab_path = format!("{}/etc/fstab", install_root);

    let mut content = fs::read_to_string(&fstab_path).unwrap_or_default();
    content.push_str("\n# Swap file\n");
    content.push_str(&swap_file_fstab_entry(config));

    fs::write(&fstab_path, content)?;
    info!("Added swap file entry to fstab");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    // ── immutable: initramfs-owned mount points ──────────────────────────────

    /// The regression: fstab listed `/`, `/usr` and `/etc` with the base
    /// `@`/`@usr`/`@etc`. Every snapshot set inherits that file on its `@etc`,
    /// so booting a set let `mount -a` mount the base subvolumes on top —
    /// hiding everything `deploytix update` had installed into the set. The
    /// initramfs mounts all three from `.deploytix-pair`; fstab must not.
    #[test]
    fn immutable_fstab_omits_the_mount_points_the_initramfs_owns() {
        for mp in ["/", "/usr", "/etc"] {
            assert!(
                crate::immutable::initramfs_owned_mount(mp),
                "{mp} must be recognised as initramfs-owned"
            );
        }
        // The writable-path binds and /tmp are *not* owned — they belong in fstab.
        for mp in ["/var", "/home", "/boot", "/tmp", "/opt", "/srv", "/root"] {
            assert!(
                !crate::immutable::initramfs_owned_mount(mp),
                "{mp} must stay in fstab"
            );
        }
    }

    #[test]
    fn immutable_fstab_note_explains_the_omission() {
        assert!(INITRAMFS_OWNED_NOTE.contains("mountcrypt"));
        assert!(INITRAMFS_OWNED_NOTE.contains(".deploytix-pair"));
        assert!(INITRAMFS_OWNED_NOTE.contains("NOT listed here"));
        // Every line is a comment, so it is safe to splice into an fstab.
        for line in INITRAMFS_OWNED_NOTE.lines() {
            assert!(
                line.is_empty() || line.starts_with('#'),
                "note line is not a comment: {line}"
            );
        }
    }

    /// The immutable model still needs writable homes for the paths that live
    /// inside the read-only root; those entries are unaffected by the omission.
    #[test]
    fn immutable_writable_paths_cover_tmp_and_the_var_binds() {
        let s = immutable_writable_paths("9f72ea22-39ab-4a60-8ce0-38a8219c376a");
        assert!(
            s.contains("subvol=@tmp"),
            "/tmp must be disk-backed @tmp, got:\n{s}"
        );
        assert!(
            !s.contains("tmpfs  /tmp  tmpfs"),
            "must not use half-RAM tmpfs for /tmp"
        );
        for (source, target) in crate::immutable::WRITABLE_BIND_PATHS {
            assert!(
                s.contains(&format!("{source}  {target}  none  bind")),
                "missing bind {source} -> {target}"
            );
        }
    }

    /// The pacman database goes the other way from the writable binds: out of
    /// the shared `/var` and into the snapshotted `/usr`. Without this entry a
    /// rollback restores the files and leaves the database describing the set
    /// that was rolled away from.
    #[test]
    fn the_pacman_database_is_bound_out_of_the_image_on_both_backends() {
        use crate::immutable::pacman_db::{DB_DIR, DB_MOUNT};

        let btrfs = immutable_writable_paths("9f72ea22-39ab-4a60-8ce0-38a8219c376a");
        assert!(
            btrfs.contains(&format!("{DB_DIR}  {DB_MOUNT}  none  bind,nofail")),
            "btrfs fstab is missing the pacman-db bind:\n{btrfs}"
        );

        // The A/B generator needs real block devices, so assert on the shared
        // entry it splices in rather than running it.
        let entry = crate::immutable::pacman_db::fstab_entry();
        assert!(entry.contains(&format!("{DB_DIR}  {DB_MOUNT}")));
    }

    // ── fsck_pass ────────────────────────────────────────────────────────────

    #[test]
    fn fsck_pass_ext4_root_returns_1() {
        assert_eq!(fsck_pass(&Filesystem::Ext4, "/"), 1);
    }

    #[test]
    fn fsck_pass_ext4_non_root_returns_2() {
        for mp in ["/usr", "/var", "/home", "/data"] {
            assert_eq!(
                fsck_pass(&Filesystem::Ext4, mp),
                2,
                "expected pass 2 for ext4 at mount point '{}'",
                mp
            );
        }
    }

    #[test]
    fn fsck_pass_non_ext4_always_returns_0() {
        let filesystems = [
            Filesystem::Btrfs,
            Filesystem::Xfs,
            Filesystem::F2fs,
            Filesystem::Zfs,
        ];
        for fs in &filesystems {
            for mp in ["/", "/usr", "/home"] {
                assert_eq!(
                    fsck_pass(fs, mp),
                    0,
                    "expected pass 0 for {:?} at '{}'",
                    fs,
                    mp
                );
            }
        }
    }
}
